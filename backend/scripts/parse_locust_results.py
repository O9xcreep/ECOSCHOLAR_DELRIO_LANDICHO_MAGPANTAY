#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
Parse Locust CSV results and generate a professional summary for thesis Table 26.

This script reads the CSV files generated by Locust and produces a formatted
report suitable for academic documentation.

Usage:
    python parse_locust_results.py [results_file_prefix]

Example:
    python parse_locust_results.py locust_results
"""
import csv
import json
import sys
from pathlib import Path
from statistics import mean, stdev


def parse_locust_results(prefix="locust_results"):
    """Parse Locust CSV results and generate summary."""

    stats_file = f"{prefix}_stats.csv"
    stats_history_file = f"{prefix}_stats_history.csv"

    if not Path(stats_file).exists():
        print(f"Error: {stats_file} not found")
        print("Run: locust -f scripts/locustfile.py --host=http://localhost:5000 -u 10 -r 2 -t 60s --headless --csv={prefix}")
        return

    # Parse stats
    endpoints = {}
    with open(stats_file, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row['Name'] == 'Total':
                total_requests = int(row['Request Count'])
                total_failures = int(row['Failure Count'])
                mean_response = float(row['Average Response Time'])
                median_response = float(row['Median Response Time'])
                min_response = float(row['Min Response Time'])
                max_response = float(row['Max Response Time'])
                rps = float(row['Requests/s'])
            else:
                endpoints[row['Name']] = {
                    'requests': int(row['Request Count']),
                    'failures': int(row['Failure Count']),
                    'mean': float(row['Average Response Time']),
                    'median': float(row['Median Response Time']),
                    'min': float(row['Min Response Time']),
                    'max': float(row['Max Response Time']),
                }

    # Calculate success rate
    success_rate = ((total_requests - total_failures) / total_requests * 100) if total_requests > 0 else 0

    # Generate report
    print("\n" + "="*70)
    print("ECOSCHOLAR API LOAD TEST RESULTS - LOCUST")
    print("="*70)
    print()

    print("OVERALL METRICS")
    print("-" * 70)
    print(f"Total Requests:           {total_requests}")
    print(f"Successful Requests:      {total_requests - total_failures}")
    print(f"Failed Requests:          {total_failures}")
    print(f"Success Rate:             {success_rate:.1f}%")
    print(f"Requests/Second (RPS):    {rps:.2f}")
    print()

    print("RESPONSE TIME (milliseconds)")
    print("-" * 70)
    print(f"Mean Response Time:       {mean_response:.2f} ms")
    print(f"Median Response Time:     {median_response:.2f} ms")
    print(f"Min Response Time:        {min_response:.2f} ms")
    print(f"Max Response Time:        {max_response:.2f} ms")
    print()

    print("PER-ENDPOINT BREAKDOWN")
    print("-" * 70)
    for endpoint, stats in sorted(endpoints.items()):
        print(f"\n{endpoint}")
        print(f"  Requests:  {stats['requests']:6d}  |  "
              f"Failures:  {stats['failures']:2d}  |  "
              f"Mean:  {stats['mean']:7.2f} ms")
    print()

    # Generate JSON for easy parsing
    summary = {
        "test_type": "Locust Load Test",
        "total_requests": total_requests,
        "successful_requests": total_requests - total_failures,
        "failed_requests": total_failures,
        "success_rate_percent": round(success_rate, 1),
        "throughput_rps": round(rps, 2),
        "throughput_rpm": round(rps * 60, 1),
        "response_time_mean_ms": round(mean_response, 2),
        "response_time_median_ms": round(median_response, 2),
        "response_time_min_ms": round(min_response, 2),
        "response_time_max_ms": round(max_response, 2),
        "endpoints": endpoints,
    }

    # Save JSON summary
    with open(f"{prefix}_summary.json", 'w') as f:
        json.dump(summary, f, indent=2)
    print(f"Summary saved to: {prefix}_summary.json")
    print()

    # Generate Table 26 format
    print("TABLE 26 FORMAT (for thesis)")
    print("-" * 70)
    print(f"Baseline (single user):          N/A (use web UI at localhost:8089)")
    print(f"Simulated peak load (10 users):")
    print(f"  Mean Response Time:            {mean_response:.2f} ms")
    print(f"  Throughput:                    {rps:.2f} req/sec ({rps*60:.1f} req/min)")
    print()

    return summary


if __name__ == "__main__":
    prefix = sys.argv[1] if len(sys.argv) > 1 else "locust_results"
    parse_locust_results(prefix)
